def _chart(h17):
    rows = []
    def row(label, cards):
        cells = ''.join(f'<td class="a-{ACT[a][1]}">{a}</td>' for a in (basic(cards, up, h17=h17, das=True, surrender=True) for up in UPS))
        return f'<tr><th>{label}</th>{cells}</tr>'
    head = '<tr><th>You</th>' + ''.join(f'<th>{UP_LABEL.get(u, u)}</th>' for u in UPS) + '</tr>'
    hard = ''.join(row(str(n), [10, n - 10] if n >= 12 else [2, n - 2]) for n in range(8, 18))
    soft = ''.join(row(f'A,{n}', [1, n]) for n in range(2, 10))
    pairs = ''.join(row(f'{"A" if n == 1 else n},{"A" if n == 1 else n}', [n, n]) for n in [1, 10, 9, 8, 7, 6, 5, 4, 3, 2])
    t = lambda name, body: f'<h3>{name}</h3><div class="chart-wrap"><table class="bs-chart"><thead>{head}</thead><tbody>{body}</tbody></table></div>'
    return t('Hard totals', hard) + t('Soft totals', soft) + t('Pairs', pairs)


